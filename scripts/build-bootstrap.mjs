import { readFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const root = new URL("../", import.meta.url)
const entrypoint = fileURLToPath(new URL("crates/narrava-loom-script/bootstrap/index.ts", root))
const output = new URL("crates/narrava-loom-script/src/bootstrap.generated.js", root)

const result = await Bun.build({
  banner: "// Generated by bun run bootstrap:build. Do not edit.\n",
  entrypoints: [entrypoint],
  format: "iife",
  minify: false,
  naming: "bootstrap.generated.js",
  outdir: fileURLToPath(new URL("crates/narrava-loom-script/src", root)),
  sourcemap: "none",
  target: "browser",
  write: !process.argv.includes("--check"),
})

if (!result.success) {
  for (const log of result.logs) console.error(log)
  process.exit(1)
}

if (process.argv.includes("--check")) {
  const [built, current] = await Promise.all([result.outputs[0].text(), readFile(output, "utf8")])
  if (built !== current) {
    throw new Error(`${output.pathname} 未同步；请运行 bun run bootstrap:build`)
  }
}
